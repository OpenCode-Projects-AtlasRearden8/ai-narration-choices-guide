/**
 * Tiny zero-dependency static server for the site.
 * Run: node scripts/serve.mjs  (or npm start)  ->  http://localhost:8642
 */
import { createServer } from 'node:http';
import { readFile } from 'node:fs/promises';
import { dirname, extname, join, normalize, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', 'site');
const PORT = process.env.PORT || 8642;

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.png': 'image/png',
  '.svg': 'image/svg+xml',
};

createServer(async (req, res) => {
  try {
    let path = decodeURIComponent(new URL(req.url, 'http://localhost').pathname);
    if (path.endsWith('/')) path += 'index.html';
    const safe = normalize(path).replace(/^(\.\.[/\\])+/, '');
    const file = resolve(ROOT, '.' + safe);
    if (!file.startsWith(resolve(ROOT))) throw new Error('outside site/');
    const body = await readFile(file);
    res.writeHead(200, { 'Content-Type': TYPES[extname(file)] || 'application/octet-stream' });
    res.end(body);
  } catch {
    res.writeHead(404, { 'Content-Type': 'text/plain; charset=utf-8' });
    res.end('Not found. Try http://localhost:' + PORT + '/\n');
  }
}).listen(PORT, () => {
  console.log('Serving site/ at http://localhost:' + PORT);
});
